<?php
$x=10;

// pre incerement
++$x;        //11
echo ("\npre increment : $x"); //11

//x=11
// post increment
$x++;          //12
echo ("\npost increment : $x"); // 12

//x=12
// pre decrement
--$x;                // 11
echo ("\npre decrement : $x");   //11

// x=11
// post decrement
$x--;             //10
echo ("\npost decrement : $x");  // 0

echo ("\n$x");